"""Generates the launcher icons and the Play Store graphics of Seven Handshakes.

The icon is a ring of seven people (dots) joined by handshakes (lines), with a gratitude
star in the middle: help travels around the ring and comes back.

Pure Python, no dependencies. Run from the repository root:

    python tools/generate_icons.py

Writes:
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon foreground (vector)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed icon, Android 13+ (vector)
  app/src/main/res/values/ic_launcher_background.xml     adaptive icon background color
  app/src/main/res/drawable/drawer_header.xml            navigation drawer header (vector)
  app/src/main/res/mipmap-anydpi-v26/ic_launcher(_round).xml
  app/src/main/res/mipmap-*/ic_launcher(_round).png      legacy icons, Android 5-7.1
  playstore/icon-512.png                                 Play Console app icon
  playstore/feature-graphic-1024x500.png                 Play Console feature graphic
"""

import math
import os
import struct
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
PLAY = os.path.join(ROOT, "playstore")

# Colors, matching MainTheme.kt
BACKGROUND = "#263238"
EDGE = "#66BB6A"
NODE = "#ECEFF1"
STAR = "#FFCA28"

# Geometry, in the 108x108 adaptive icon canvas. The safe zone is a circle of radius 33.
C = 54.0
RING_RADIUS = 22.0
NODE_RADIUS = 4.4
EDGE_WIDTH = 2.6
STAR_OUTER = 9.5
STAR_INNER = 4.0


def ring_nodes():
    return [
        (C + RING_RADIUS * math.cos(-math.pi / 2 + 2 * math.pi * i / 7),
         C + RING_RADIUS * math.sin(-math.pi / 2 + 2 * math.pi * i / 7))
        for i in range(7)
    ]


def star_points():
    pts = []
    for i in range(10):
        r = STAR_OUTER if i % 2 == 0 else STAR_INNER
        a = -math.pi / 2 + math.pi * i / 5
        pts.append((C + r * math.cos(a), C + 0.5 + r * math.sin(a)))
    return pts


def network():
    """The wider network of the feature graphic: polylines of faint handshakes and their people."""
    nodes = ring_nodes()
    left = min(nodes, key=lambda p: p[0])
    right = max(nodes, key=lambda p: p[0])
    lines, people = [], []
    for side, start in ((-1, left), (1, right)):
        chain = [start] + [(C + side * dx, C + dy) for dx, dy in ((38, -10), (50, 6), (64, -4), (78, 10))]
        branch = [chain[2], (C + side * 56, C + 22), (C + side * 70, C + 30)]
        lines += [chain, branch]
        people += chain[1:] + branch[1:]
    return lines, people


# Feature graphic: 1024x500 pixels, 7 pixels per canvas unit, the ring in the middle.
FEATURE_SCALE = 7.0
FEATURE_X0 = C - 512 / FEATURE_SCALE
FEATURE_Y0 = C - 250 / FEATURE_SCALE
FAINT_ALPHA = 0.35


def mix(color, over, alpha):
    """[color] at [alpha] over [over], as an opaque hex color."""
    a, b = rgba(color), rgba(over)
    return "#%02X%02X%02X" % tuple(round((x * alpha + y * (1 - alpha)) * 255) for x, y in zip(a[:3], b[:3]))


# ---------------------------------------------------------------- vector drawables

def f(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def circle_path(cx, cy, r):
    return "M%s,%s a%s,%s 0 1,0 %s,0 a%s,%s 0 1,0 %s,0 Z" % (
        f(cx - r), f(cy), f(r), f(r), f(2 * r), f(r), f(r), f(-2 * r))


def polygon_path(pts, close=True):
    d = "M" + " L".join("%s,%s" % (f(x), f(y)) for x, y in pts)
    return d + (" Z" if close else "")


def vector_xml(edge, node, star):
    nodes = ring_nodes()
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py, do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- Handshakes: the ring that joins seven people -->
    <path
        android:pathData="{polygon_path(nodes)}"
        android:strokeColor="{edge}"
        android:strokeWidth="{f(EDGE_WIDTH)}"
        android:strokeLineJoin="round" />
    <!-- People -->
    <path
        android:fillColor="{node}"
        android:pathData="{' '.join(circle_path(x, y, NODE_RADIUS) for x, y in nodes)}" />
    <!-- Gratitude -->
    <path
        android:fillColor="{star}"
        android:pathData="{polygon_path(star_points())}" />
</vector>
"""


def drawer_header_xml():
    """The feature graphic as a vector drawable, for the navigation drawer header."""
    width, height = 1024 / FEATURE_SCALE, 500 / FEATURE_SCALE
    lines, people = network()
    nodes = ring_nodes()
    faint_edge = "#%02X%s" % (round(FAINT_ALPHA * 255), EDGE.lstrip("#"))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py, do not edit by hand. Same picture as playstore/feature-graphic-1024x500.png. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{f(width * 2.5)}dp"
    android:height="{f(height * 2.5)}dp"
    android:viewportWidth="{f(width)}"
    android:viewportHeight="{f(height)}">
    <path
        android:fillColor="{BACKGROUND}"
        android:pathData="M0,0 H{f(width)} V{f(height)} H0 Z" />
    <group
        android:translateX="{f(-FEATURE_X0)}"
        android:translateY="{f(-FEATURE_Y0)}">
        <!-- The wider network of faint handshakes -->
        <path
            android:pathData="{' '.join(polygon_path(line, close=False) for line in lines)}"
            android:strokeColor="{faint_edge}"
            android:strokeWidth="{f(EDGE_WIDTH * 0.8)}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
        <path
            android:fillColor="{mix(NODE, BACKGROUND, FAINT_ALPHA)}"
            android:pathData="{' '.join(circle_path(x, y, NODE_RADIUS * 0.8) for x, y in people)}" />
        <!-- The ring of the app icon -->
        <path
            android:pathData="{polygon_path(nodes)}"
            android:strokeColor="{EDGE}"
            android:strokeWidth="{f(EDGE_WIDTH)}"
            android:strokeLineJoin="round" />
        <path
            android:fillColor="{NODE}"
            android:pathData="{' '.join(circle_path(x, y, NODE_RADIUS) for x, y in nodes)}" />
        <path
            android:fillColor="{STAR}"
            android:pathData="{polygon_path(star_points())}" />
    </group>
</vector>
"""


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py, do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

BACKGROUND_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py, do not edit by hand. -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
"""


# ---------------------------------------------------------------- rasterizer

def rgba(hex_color, alpha=1.0):
    h = hex_color.lstrip("#")
    return (int(h[0:2], 16) / 255, int(h[2:4], 16) / 255, int(h[4:6], 16) / 255, alpha)


def sd_circle(cx, cy, r):
    return (lambda x, y: math.hypot(x - cx, y - cy) - r), (cx - r, cy - r, cx + r, cy + r)


def sd_segment(ax, ay, bx, by, w):
    dx, dy = bx - ax, by - ay
    ll = dx * dx + dy * dy

    def d(x, y):
        t = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / ll))
        return math.hypot(x - ax - t * dx, y - ay - t * dy) - w / 2

    h = w / 2
    return d, (min(ax, bx) - h, min(ay, by) - h, max(ax, bx) + h, max(ay, by) + h)


def sd_polygon(pts):
    n = len(pts)

    def d(x, y):
        best = float("inf")
        inside = False
        j = n - 1
        for i in range(n):
            xi, yi = pts[i]
            xj, yj = pts[j]
            ex, ey = xj - xi, yj - yi
            wx, wy = x - xi, y - yi
            t = max(0.0, min(1.0, (wx * ex + wy * ey) / (ex * ex + ey * ey)))
            best = min(best, math.hypot(wx - t * ex, wy - t * ey))
            if (yi > y) != (yj > y) and x < xi + (y - yi) * ex / ey:
                inside = not inside
            j = i
        return -best if inside else best

    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return d, (min(xs), min(ys), max(xs), max(ys))


def sd_round_rect(x0, y0, x1, y1, r):
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    hx, hy = (x1 - x0) / 2 - r, (y1 - y0) / 2 - r

    def d(x, y):
        qx, qy = abs(x - cx) - hx, abs(y - cy) - hy
        return math.hypot(max(qx, 0), max(qy, 0)) + min(max(qx, qy), 0) - r

    return d, (x0, y0, x1, y1)


def icon_layers():
    nodes = ring_nodes()
    layers = []
    for i in range(7):
        a, b = nodes[i], nodes[(i + 1) % 7]
        layers.append((sd_segment(a[0], a[1], b[0], b[1], EDGE_WIDTH), rgba(EDGE)))
    for x, y in nodes:
        layers.append((sd_circle(x, y, NODE_RADIUS), rgba(NODE)))
    layers.append((sd_polygon(star_points()), rgba(STAR)))
    return layers


def render(width, height, x0, y0, scale, layers, clip=None):
    """Renders layers, given as ((sdf, bbox), color), into RGBA rows.

    Pixel (px, py) samples scene point (x0 + (px + .5) / scale, y0 + (py + .5) / scale).
    Edges are antialiased from the signed distance. clip, an (sdf, bbox), masks everything.
    """
    pixel = 1.0 / scale
    rows = []
    for py in range(height):
        y = y0 + (py + 0.5) * pixel
        row = bytearray()
        for px in range(width):
            x = x0 + (px + 0.5) * pixel
            r = g = b = a = 0.0
            for (sdf, (bx0, by0, bx1, by1)), (cr, cg, cb, ca) in layers:
                if x < bx0 - pixel or x > bx1 + pixel or y < by0 - pixel or y > by1 + pixel:
                    continue
                cov = max(0.0, min(1.0, 0.5 - sdf(x, y) / pixel)) * ca
                if cov <= 0:
                    continue
                r = cr * cov + r * (1 - cov)
                g = cg * cov + g * (1 - cov)
                b = cb * cov + b * (1 - cov)
                a = cov + a * (1 - cov)
            if clip is not None:
                m = max(0.0, min(1.0, 0.5 - clip[0](x, y) / pixel))
                r, g, b, a = r * m, g * m, b * m, a * m
            # r, g, b are premultiplied
            if a > 0:
                row += bytes((round(r / a * 255), round(g / a * 255), round(b / a * 255), round(a * 255)))
            else:
                row += b"\0\0\0\0"
        rows.append(bytes(row))
    return rows


def write_png(path, width, height, rows, alpha=True):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if alpha:
        raw = b"".join(b"\0" + row for row in rows)
        color_type = 6
    else:
        raw = b"".join(b"\0" + bytes(v for i, v in enumerate(row) if i % 4 != 3) for row in rows)
        color_type = 2

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    with open(path, "wb") as out:
        out.write(b"\x89PNG\r\n\x1a\n")
        out.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0)))
        out.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        out.write(chunk(b"IEND", b""))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write(text)


# ---------------------------------------------------------------- outputs

def main():
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), vector_xml(EDGE, NODE, STAR))
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
          vector_xml("#FFFFFFFF", "#FFFFFFFF", "#FFFFFFFF"))
    write(os.path.join(RES, "values", "ic_launcher_background.xml"), BACKGROUND_XML)
    write(os.path.join(RES, "drawable", "drawer_header.xml"), drawer_header_xml())
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE_XML)
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher_round.xml"), ADAPTIVE_XML)

    content = icon_layers()

    # Legacy icons (Android 5-7.1): the central 72 units of the canvas fill the 48dp icon,
    # inside a 44dp shape, as launchers of that time expect.
    bg = rgba(BACKGROUND)
    square = sd_round_rect(C - 33, C - 33, C + 33, C + 33, 6)
    circle = sd_circle(C, C, 33)
    for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        scale = size / 72.0
        for name, shape in (("ic_launcher", square), ("ic_launcher_round", circle)):
            rows = render(size, size, C - 36, C - 36, scale, [(shape, bg)] + content, clip=shape)
            write_png(os.path.join(RES, "mipmap-" + density, name + ".png"), size, size, rows)
            print("mipmap-%s/%s.png" % (density, name))

    # Play Console icon: 512x512, full bleed square (Play rounds the corners itself), no alpha.
    full = ((lambda x, y: -1.0), (-1e9, -1e9, 1e9, 1e9))
    view = 76.0
    rows = render(512, 512, C - view / 2, C - view / 2, 512 / view, [(full, bg)] + content)
    write_png(os.path.join(PLAY, "icon-512.png"), 512, 512, rows, alpha=False)
    print("playstore/icon-512.png")

    # Feature graphic: 1024x500, the ring in the middle of a wider network of faint handshakes.
    lines, people = network()
    faint_edge = rgba(EDGE, FAINT_ALPHA)
    # Opaque, so the lines behind do not show through
    faint_node = rgba(mix(NODE, BACKGROUND, FAINT_ALPHA))
    network_layers = []
    for line in lines:
        for a, b in zip(line, line[1:]):
            network_layers.append((sd_segment(a[0], a[1], b[0], b[1], EDGE_WIDTH * 0.8), faint_edge))
    for x, y in people:
        network_layers.append((sd_circle(x, y, NODE_RADIUS * 0.8), faint_node))
    rows = render(1024, 500, FEATURE_X0, FEATURE_Y0, FEATURE_SCALE, [(full, bg)] + network_layers + content)
    write_png(os.path.join(PLAY, "feature-graphic-1024x500.png"), 1024, 500, rows, alpha=False)
    print("playstore/feature-graphic-1024x500.png")


if __name__ == "__main__":
    main()
